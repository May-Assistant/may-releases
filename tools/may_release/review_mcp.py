"""May's comment server for review.py: a stand-in for claude-code-action's github_inline_comment MCP server.

Claude Code starts it over stdio as `github_inline_comment`, so the pinned code-review command's
mcp__github_inline_comment__create_inline_comment works unchanged. It adds create_summary_comment, which takes
the place of `gh pr comment` (not allowed in the review), so every comment carries the footer.

It posts only to the pull request review.py checked (MAY_PR_NUMBER) at the head it fetched (MAY_REVIEW_HEAD):
a commit_id naming any other commit is refused, and before each post it reads the pull request again and posts
nothing once it is closed, a draft, retargeted or at another head. At most MAX_COMMENTS post per run. Every body
gets a head marker and May's attribution footer. A body holding the review token in any spelling (raw, with
separators, base64 or hex) is refused, and token-shaped text is redacted (security review of #21, M1). Nothing
in a body can make a viewer's browser or GitHub's image proxy fetch from elsewhere (re-review of #21, L-b): outside
code, raw HTML is escaped, image syntax becomes a plain link, and every link or bare URL whose host is not
github.com is replaced. Code blocks and spans are left as written (GitHub renders no HTML, image or link in them),
so a suggestion's code is intact. The cap is counted from MAY_REVIEW_POSTED, so a restart can't reset it (L-c). As
in the action, a call without confirmed: true posts nothing.

The review token comes from MAY_REVIEW_TOKEN_FILE, a 0600 file the model may not read; it is never in Claude
Code's environment (review of #21, H1).

It writes nothing to stdout but its JSON-RPC answers, and nothing at all to stderr. To MAY_REVIEW_POSTED it
writes one word per event (started, inline, summary, failed, refused), which review.py counts; never a body or a
path.
"""

import base64
import json
import os
import re
import sys
import urllib.error
import urllib.request

APP_REPO = "May-Assistant/may-app"
API = "https://api.github.com"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
MAX_BODY = 60_000
MAX_COMMENTS = 30
FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
CODE_SPAN = re.compile(r"(`+)(?:(?!\1)[\s\S])+?\1")
# A link's or image's target, an autolink, a bare URL GitHub would link (http, https, protocol-relative, www.).
LINK_TARGET = re.compile(r"""\]\(\s*<?([^)\s>]*)>?(?:\s+["'(][^)]*)?\)""")
REFERENCE = re.compile(r"(?m)^( {0,3}\[[^\]\n]+\]:[ \t]*)<?(\S+?)>?([ \t].*)?$")
BARE_URL = re.compile(r"(?i)\b(?:https?://|www\.)[^\s<>()\[\]]+|(?<![\w:/])//[^\s<>()\[\]/]+\.[^\s<>()\[\]]+")
REMOVED = "(link removed)"
SHA = re.compile(r"[0-9a-f]{40}")
TOKEN_SHAPED = re.compile(r"github_pat_[A-Za-z0-9_]+|gh[opsur]_[A-Za-z0-9]+|sk-ant-[A-Za-z0-9_-]+")
PROTOCOL = "2025-06-18"
INLINE = {
    "name": "create_inline_comment",
    "description": "Create an inline comment on a specific line or lines in a PR file",
    "inputSchema": {"type": "object", "required": ["path", "body"], "properties": {
        "path": {"type": "string", "description": "The file path to comment on (e.g., 'src/index.js')"},
        "body": {"type": "string", "description": (
            "The comment text (supports markdown and GitHub code suggestion blocks). For code suggestions, use: "
            "```suggestion\\nreplacement code\\n```. IMPORTANT: The suggestion block will REPLACE the ENTIRE line "
            "range (single line or startLine to line). Ensure the replacement is syntactically complete and valid - "
            "it must work as a drop-in replacement for the selected lines.")},
        "line": {"type": "integer", "minimum": 1,
                 "description": "Line number for single-line comments, or the end line of a multi-line comment"},
        "startLine": {"type": "integer", "minimum": 1,
                      "description": "Start line for multi-line comments (use with line parameter for the end line)"},
        "side": {"type": "string", "enum": ["LEFT", "RIGHT"], "default": "RIGHT",
                 "description": "Side of the diff to comment on: LEFT (old code) or RIGHT (new code)"},
        "commit_id": {"type": "string", "description": "Leave out: comments always go on the reviewed head"},
        "confirmed": {"type": "boolean", "description": "Set true to post. Without it nothing is posted."}}},
}
SUMMARY = {
    "name": "create_summary_comment",
    "description": "Post the review's summary comment on the pull request (in place of gh pr comment)",
    "inputSchema": {"type": "object", "required": ["body"], "properties": {
        "body": {"type": "string", "description": "The comment text, in markdown"}}},
}


class Refusal(ValueError):
    pass


def settings(environ):
    number, head, path = environ.get("MAY_PR_NUMBER", ""), environ.get("MAY_REVIEW_HEAD", ""), environ.get("MAY_REVIEW_TOKEN_FILE", "")
    if not re.fullmatch(r"[1-9][0-9]{0,6}", number) or not SHA.fullmatch(head) or not path:
        return None
    try:
        with open(path, encoding="utf-8") as stream:
            token = stream.read().strip()
    except OSError:
        return None
    if len(token) < 20:
        return None
    posted = environ.get("MAY_REVIEW_POSTED", "")
    if not posted:
        return None
    return {"number": int(number), "head": head, "token": token, "posted": posted}


def note(config, word):
    with open(config["posted"], "a", encoding="utf-8") as stream:
        stream.write(word + "\n")


def attempts(config):
    """Posts tried this run (posted or failed), from MAY_REVIEW_POSTED, which outlives a restart of this server."""
    try:
        with open(config["posted"], encoding="utf-8") as stream:
            words = stream.read().split()
    except OSError:
        return 0
    return sum(words.count(w) for w in ("inline", "summary", "failed"))


def allowed_url(url):
    """github.com over https, or a link within the page or repository (#anchor, a relative path)."""
    if re.match(r"(?i)https://github\.com(/|$)", url):
        return True
    return not re.match(r"(?i)([a-z][a-z0-9+.-]*:|//|www\.)", url) and not url.startswith("\\")


def neutral_text(text):
    """Text outside code: no raw HTML, no image, and no link or URL to any host but github.com."""
    text = text.replace("<", "&lt;")
    text = text.replace("![", "[")
    text = LINK_TARGET.sub(lambda m: m.group(0) if allowed_url(m.group(1)) else "](#)", text)
    text = REFERENCE.sub(lambda m: m.group(0) if allowed_url(m.group(2)) else m.group(1) + "#", text)
    return BARE_URL.sub(lambda m: m.group(0) if allowed_url(m.group(0)) else REMOVED, text)


def neutralised(body):
    """The body with neutral_text applied outside fenced code blocks and code spans."""
    out, prose, fence = [], [], None
    def flush():
        if prose:
            text = "".join(prose)
            parts, last = [], 0
            for span in CODE_SPAN.finditer(text):
                parts += [neutral_text(text[last:span.start()]), span.group(0)]
                last = span.end()
            out.append("".join(parts) + neutral_text(text[last:]))
            prose.clear()
    for line in body.splitlines(keepends=True):
        opener = FENCE.match(line)
        if fence is None and opener:
            flush()
            fence = opener.group(1)
            out.append(line)
        elif fence is not None:
            out.append(line)
            if re.match(r"^ {0,3}" + re.escape(fence[0]) + "{" + str(len(fence)) + r",}\s*$", line):
                fence = None
        else:
            prose.append(line)
    flush()
    return "".join(out)


def spellings(token):
    """The token as text could carry it: raw, base64 (standard and URL-safe, with or without padding) and hex."""
    raw = token.encode()
    encoded = {base64.b64encode(raw).decode(), base64.urlsafe_b64encode(raw).decode(), raw.hex()}
    return {token} | encoded | {e.rstrip("=") for e in encoded}


def holds(text, token):
    """True when text carries the token in any spelling, with any separators or case in between."""
    squeezed = re.sub(r"[^A-Za-z0-9]", "", text).lower()
    return any(s in text or re.sub(r"[^A-Za-z0-9]", "", s).lower() in squeezed for s in spellings(token))


def body_of(args, config):
    body = args.get("body")
    if not isinstance(body, str) or not body.strip():
        raise Refusal("body must be non-empty text")
    if len(body) > MAX_BODY:
        raise Refusal("body is too long")
    if holds(body, config["token"]):
        raise Refusal("body holds a credential")
    return neutralised(TOKEN_SHAPED.sub("[redacted]", body)) + f"\n\n<!-- may-app-review head={config['head']} -->" + FOOTER


def positive(value):
    return isinstance(value, int) and not isinstance(value, bool) and value >= 1


def inline_request(args, config):
    path, line, start, side = args.get("path"), args.get("line"), args.get("startLine"), args.get("side", "RIGHT")
    if not isinstance(path, str) or not path or path.startswith("/") or ".." in path.split("/") or "\n" in path:
        raise Refusal("path must be a file path relative to the repository root")
    if not positive(line):
        raise Refusal("line must be a positive line number")
    if start is not None and (not positive(start) or start > line):
        raise Refusal("startLine must be a positive line number no greater than line")
    if side not in ("LEFT", "RIGHT"):
        raise Refusal("side must be LEFT or RIGHT")
    if args.get("commit_id") not in (None, "", config["head"]):
        raise Refusal("commit_id must be left out: comments go on the reviewed head " + config["head"])
    payload = {"body": body_of(args, config), "commit_id": config["head"], "path": path, "line": line, "side": side}
    if start is not None and start < line:
        payload.update(start_line=start, start_side=side)
    return f"/repos/{APP_REPO}/pulls/{config['number']}/comments", payload


def github(method, path, payload, token):
    """One GitHub API call: (status, parsed JSON or None). Nothing from it is printed."""
    request = urllib.request.Request(API + path, data=None if payload is None else json.dumps(payload).encode(),
                                     method=method, headers={
        "Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.status, json.loads(response.read() or b"null")
    except urllib.error.HTTPError as error:
        return error.code, None
    except (urllib.error.URLError, TimeoutError, ValueError):
        return 0, None


def still_reviewable(config, call_api):
    """The pull request is still open, ready, against may-app main and at the reviewed head (review of #21, L1)."""
    status, pull = call_api("GET", f"/repos/{APP_REPO}/pulls/{config['number']}", None, config["token"])
    return status == 200 and isinstance(pull, dict) and pull.get("state") == "open" and pull.get("draft") is False \
        and (pull.get("base") or {}).get("ref") == "main" and (pull.get("head") or {}).get("sha") == config["head"]


def call(name, args, config, call_api):
    if not isinstance(args, dict):
        args = {}
    if name in (INLINE["name"], SUMMARY["name"]) and attempts(config) >= MAX_COMMENTS:
        note(config, "refused")
        return True, f"Not posted: this review has already posted {MAX_COMMENTS} comments, the most one run may"
    try:
        if name == INLINE["name"]:
            if args.get("confirmed") is not True:
                return False, "Not posted: only a call with confirmed: true posts. The tool works; no need to test it."
            kind, (path, payload) = "inline", inline_request(args, config)
        elif name == SUMMARY["name"]:
            kind, path, payload = "summary", f"/repos/{APP_REPO}/issues/{config['number']}/comments", {"body": body_of(args, config)}
        else:
            return True, "Unknown tool"
    except Refusal as refusal:
        note(config, "refused")
        return True, "Not posted: " + refusal.args[0]
    if not still_reviewable(config, call_api):
        note(config, "refused")
        return True, "Not posted: the pull request is no longer open and ready at the reviewed head"
    status, _ = call_api("POST", path, payload, config["token"])
    if status == 201:
        note(config, kind)
        return False, json.dumps({"success": True, "posted": kind})
    note(config, "failed")
    return True, f"Not posted: GitHub answered {status or 'nothing'}"


def answer(message, config, call_api):
    """The JSON-RPC answer to one message, or None for a notification."""
    if not isinstance(message, dict) or "id" not in message:
        return None
    method, params = message.get("method"), message.get("params") or {}
    if method == "initialize":
        version = params.get("protocolVersion") if isinstance(params.get("protocolVersion"), str) else PROTOCOL
        result = {"protocolVersion": version, "capabilities": {"tools": {}},
                  "serverInfo": {"name": "may-review-comments", "version": "1"}}
    elif method == "ping":
        result = {}
    elif method == "tools/list":
        result = {"tools": [INLINE, SUMMARY]}
    elif method == "tools/call":
        failed, text = call(params.get("name"), params.get("arguments"), config, call_api)
        result = {"content": [{"type": "text", "text": text}], "isError": failed}
    else:
        return {"jsonrpc": "2.0", "id": message["id"], "error": {"code": -32601, "message": "Method not found"}}
    return {"jsonrpc": "2.0", "id": message["id"], "result": result}


def serve(stdin, stdout, config, call_api=github):
    note(config, "started")
    for line in stdin:
        try:
            message = json.loads(line)
        except ValueError:
            continue
        reply = answer(message, config, call_api)
        if reply is not None:
            stdout.write(json.dumps(reply) + "\n")
            stdout.flush()


if __name__ == "__main__":
    sys.stderr = open(os.devnull, "w")
    found = settings(os.environ)
    if found is None:
        sys.exit(1)
    try:
        serve(sys.stdin, sys.stdout, found)
    except Exception:
        sys.exit(1)
