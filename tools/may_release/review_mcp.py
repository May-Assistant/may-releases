"""May's comment server for review.py: a stand-in for claude-code-action's github_inline_comment MCP server.

Claude Code starts it over stdio as `github_inline_comment`, so the pinned code-review command's
mcp__github_inline_comment__create_inline_comment works unchanged. It adds create_summary_comment, which takes
the place of `gh pr comment` (not allowed in the review), so every comment carries the footer.

It posts only to the pull request review.py checked (MAY_PR_NUMBER) at the head it fetched (MAY_REVIEW_HEAD):
a commit_id naming any other commit is refused. Every body gets a head marker and May's attribution footer, and
token-shaped text is redacted from it. As in the action, a call without confirmed: true posts nothing.

It writes nothing to stdout but its JSON-RPC answers, and nothing at all to stderr. To MAY_REVIEW_POSTED it
writes one word per event (started, inline, summary, failed), which review.py counts; never a body or a path.
"""

import json
import os
import re
import sys
import urllib.error
import urllib.request

APP_REPO = "May-Assistant/may-app"
API = "https://api.github.com"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
MAX_BODY = 60_000
SHA = re.compile(r"[0-9a-f]{40}")
TOKEN_SHAPED = re.compile(r"github_pat_[A-Za-z0-9_]+|gh[opsur]_[A-Za-z0-9]+|sk-ant-[A-Za-z0-9_-]+")
PROTOCOL = "2025-06-18"
INLINE = {
    "name": "create_inline_comment",
    "description": "Create an inline comment on a specific line or lines in a PR file",
    "inputSchema": {"type": "object", "required": ["path", "body"], "properties": {
        "path": {"type": "string", "description": "The file path to comment on (e.g., 'src/index.js')"},
        "body": {"type": "string", "description": (
            "The comment text (supports markdown and GitHub code suggestion blocks). For code suggestions, use: "
            "```suggestion\\nreplacement code\\n```. IMPORTANT: The suggestion block will REPLACE the ENTIRE line "
            "range (single line or startLine to line). Ensure the replacement is syntactically complete and valid - "
            "it must work as a drop-in replacement for the selected lines.")},
        "line": {"type": "integer", "minimum": 1,
                 "description": "Line number for single-line comments, or the end line of a multi-line comment"},
        "startLine": {"type": "integer", "minimum": 1,
                      "description": "Start line for multi-line comments (use with line parameter for the end line)"},
        "side": {"type": "string", "enum": ["LEFT", "RIGHT"], "default": "RIGHT",
                 "description": "Side of the diff to comment on: LEFT (old code) or RIGHT (new code)"},
        "commit_id": {"type": "string", "description": "Leave out: comments always go on the reviewed head"},
        "confirmed": {"type": "boolean", "description": "Set true to post. Without it nothing is posted."}}},
}
SUMMARY = {
    "name": "create_summary_comment",
    "description": "Post the review's summary comment on the pull request (in place of gh pr comment)",
    "inputSchema": {"type": "object", "required": ["body"], "properties": {
        "body": {"type": "string", "description": "The comment text, in markdown"}}},
}


class Refusal(ValueError):
    pass


def settings(environ):
    number, head, token = environ.get("MAY_PR_NUMBER", ""), environ.get("MAY_REVIEW_HEAD", ""), environ.get("GH_TOKEN", "")
    if not re.fullmatch(r"[1-9][0-9]{0,6}", number) or not SHA.fullmatch(head) or not token or token.startswith("${"):
        return None
    return {"number": int(number), "head": head, "token": token, "posted": environ.get("MAY_REVIEW_POSTED")}


def note(config, word):
    if config.get("posted"):
        with open(config["posted"], "a", encoding="utf-8") as stream:
            stream.write(word + "\n")


def redacted(text, token):
    if len(token) >= 8:
        text = text.replace(token, "[redacted]")
    return TOKEN_SHAPED.sub("[redacted]", text)


def body_of(args, config):
    body = args.get("body")
    if not isinstance(body, str) or not body.strip():
        raise Refusal("body must be non-empty text")
    if len(body) > MAX_BODY:
        raise Refusal("body is too long")
    return redacted(body, config["token"]) + f"\n\n<!-- may-app-review head={config['head']} -->" + FOOTER


def positive(value):
    return isinstance(value, int) and not isinstance(value, bool) and value >= 1


def inline_request(args, config):
    path, line, start, side = args.get("path"), args.get("line"), args.get("startLine"), args.get("side", "RIGHT")
    if not isinstance(path, str) or not path or path.startswith("/") or ".." in path.split("/") or "\n" in path:
        raise Refusal("path must be a file path relative to the repository root")
    if not positive(line):
        raise Refusal("line must be a positive line number")
    if start is not None and (not positive(start) or start > line):
        raise Refusal("startLine must be a positive line number no greater than line")
    if side not in ("LEFT", "RIGHT"):
        raise Refusal("side must be LEFT or RIGHT")
    if args.get("commit_id") not in (None, "", config["head"]):
        raise Refusal("commit_id must be left out: comments go on the reviewed head " + config["head"])
    payload = {"body": body_of(args, config), "commit_id": config["head"], "path": path, "line": line, "side": side}
    if start is not None and start < line:
        payload.update(start_line=start, start_side=side)
    return f"/repos/{APP_REPO}/pulls/{config['number']}/comments", payload


def github_post(path, payload, token):
    """POST to the GitHub API; the status code, never the response body."""
    request = urllib.request.Request(API + path, data=json.dumps(payload).encode(), method="POST", headers={
        "Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.status
    except urllib.error.HTTPError as error:
        return error.code
    except (urllib.error.URLError, TimeoutError):
        return 0


def call(name, args, config, post):
    if not isinstance(args, dict):
        args = {}
    try:
        if name == INLINE["name"]:
            if args.get("confirmed") is not True:
                return False, "Not posted: only a call with confirmed: true posts. The tool works; no need to test it."
            kind, (path, payload) = "inline", inline_request(args, config)
        elif name == SUMMARY["name"]:
            kind, path, payload = "summary", f"/repos/{APP_REPO}/issues/{config['number']}/comments", {"body": body_of(args, config)}
        else:
            return True, "Unknown tool"
    except Refusal as refusal:
        return True, "Not posted: " + refusal.args[0]
    status = post(path, payload, config["token"])
    if status == 201:
        note(config, kind)
        return False, json.dumps({"success": True, "posted": kind})
    note(config, "failed")
    return True, f"Not posted: GitHub answered {status or 'nothing'}"


def answer(message, config, post):
    """The JSON-RPC answer to one message, or None for a notification."""
    if not isinstance(message, dict) or "id" not in message:
        return None
    method, params = message.get("method"), message.get("params") or {}
    if method == "initialize":
        version = params.get("protocolVersion") if isinstance(params.get("protocolVersion"), str) else PROTOCOL
        result = {"protocolVersion": version, "capabilities": {"tools": {}},
                  "serverInfo": {"name": "may-review-comments", "version": "1"}}
    elif method == "ping":
        result = {}
    elif method == "tools/list":
        result = {"tools": [INLINE, SUMMARY]}
    elif method == "tools/call":
        failed, text = call(params.get("name"), params.get("arguments"), config, post)
        result = {"content": [{"type": "text", "text": text}], "isError": failed}
    else:
        return {"jsonrpc": "2.0", "id": message["id"], "error": {"code": -32601, "message": "Method not found"}}
    return {"jsonrpc": "2.0", "id": message["id"], "result": result}


def serve(stdin, stdout, config, post=github_post):
    note(config, "started")
    for line in stdin:
        try:
            message = json.loads(line)
        except ValueError:
            continue
        reply = answer(message, config, post)
        if reply is not None:
            stdout.write(json.dumps(reply) + "\n")
            stdout.flush()


if __name__ == "__main__":
    sys.stderr = open(os.devnull, "w")
    found = settings(os.environ)
    if found is None:
        sys.exit(1)
    try:
        serve(sys.stdin, sys.stdout, found)
    except Exception:
        sys.exit(1)
